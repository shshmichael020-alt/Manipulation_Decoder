import {
  AIWritingAssessment,
  AIWritingVerdict,
  SignalStrength,
  AIWritingCharacteristic,
} from "@/types/analyzer";
import { TextStats } from "./text-stats";

/**
 * AI-Writing Likelihood Heuristic Engine
 *
 * NOTE: This is an explainable heuristic analysis based on linguistic markers,
 * NOT a neural classifier or definitive proof of authorship.
 * Both false positives (eloquent humans) and false negatives (terse LLM outputs)
 * are common in stylometric heuristics.
 */
export function analyzeAIWritingLikelihood(
  text: string,
  stats: TextStats
): AIWritingAssessment {
  const characteristics: AIWritingCharacteristic[] = [];
  let signalPoints = 0;

  // If text is too short (< 25 words or < 120 chars), it is inconclusive
  if (stats.wordCount < 25 || stats.characterCount < 120) {
    return {
      verdict: "INCONCLUSIVE",
      verdictLabel: "Inconclusive — Insufficient Evidence",
      signalStrength: "VERY_LOW",
      signalScore: 0,
      detectedCharacteristics: [
        {
          id: "short_length",
          title: "Sample Too Short for Stylometric Heuristics",
          description:
            "The message contains under 25 words. Reliable linguistic structural analysis requires longer prose samples.",
          metricScore: 0,
        },
      ],
      linguisticMetrics: {
        averageSentenceLength: stats.averageSentenceLength,
        sentenceLengthStdDev: stats.sentenceLengthStdDev,
        lexicalDiversityTTR: stats.lexicalDiversityTTR,
        formulaicTransitionCount: stats.transitionPhraseCount,
        uniformityIndex: 0,
      },
      confidenceNotes:
        "High uncertainty. Heuristic analysis on brief snippets or single sentences cannot reliably distinguish between human and machine authorship.",
      disclaimer:
        "Experimental heuristic estimation only. This does not represent a machine learning classification or verified authorship proof. Human writing can be falsely flagged, and AI text can emulate human style.",
    };
  }

  // 1. Uniformity of sentence lengths (Low variance with moderate to high sentence count)
  // AI models often output balanced, rhythmic sentences of 14-22 words with very low standard deviation.
  let uniformityIndex = 0;
  if (stats.sentenceCount >= 3) {
    const relativeStdDev =
      stats.averageSentenceLength > 0
        ? stats.sentenceLengthStdDev / stats.averageSentenceLength
        : 1;

    // Relative standard deviation < 0.28 indicates unusually rhythmic/uniform cadence
    if (relativeStdDev < 0.28 && stats.averageSentenceLength >= 10) {
      uniformityIndex = Math.min(
        100,
        Math.round((1 - relativeStdDev) * 100)
      );
      signalPoints += 25;
      characteristics.push({
        id: "uniform_cadence",
        title: "Unusually Uniform Sentence Lengths",
        description: `Sentences exhibit a tight standard deviation of ${stats.sentenceLengthStdDev} words around an average of ${stats.averageSentenceLength} words per sentence, indicating a machine-like rhythmic cadence.`,
        metricScore: uniformityIndex,
      });
    } else {
      uniformityIndex = Math.round(Math.max(0, (1 - relativeStdDev) * 50));
    }
  }

  // 2. Formulaic corporate or epistolary openings and closings
  if (stats.formulaicOpenings.length > 0) {
    signalPoints += 15;
    characteristics.push({
      id: "formulaic_opening",
      title: "Formulaic Polite Greeting / Hook",
      description:
        "Contains standardized boilerplate epistolary openings frequently generated by default LLM system prompts.",
      observedEvidence: stats.formulaicOpenings.join(", "),
    });
  }

  if (stats.formulaicClosings.length > 0) {
    signalPoints += 15;
    characteristics.push({
      id: "formulaic_closing",
      title: "Formulaic Polite Closure",
      description:
        "Uses textbook courteous concluding phrases (e.g. 'Please do not hesitate to reach out', 'Thank you for your prompt attention').",
      observedEvidence: stats.formulaicClosings.join(", "),
    });
  }

  // 3. Dense transition connectors
  // LLMs heavily utilize formal transitions ("Furthermore", "Moreover", "Additionally", "Consequently")
  if (stats.transitionPhraseCount >= 2) {
    const transitionRatio = stats.transitionPhraseCount / (stats.sentenceCount || 1);
    if (transitionRatio >= 0.4 || stats.transitionPhraseCount >= 3) {
      signalPoints += 22;
      characteristics.push({
        id: "frequent_transitions",
        title: "High Density of Formal Connectors",
        description: `Found ${stats.transitionPhraseCount} formal discourse markers (${stats.detectedTransitions.slice(0, 3).join(", ")}) which frequently characterize structured AI prose.`,
        observedEvidence: stats.detectedTransitions.join(", "),
      });
    }
  }

  // 4. Overly polished / Balanced tone markers
  const lowerText = text.toLowerCase();
  const balancedHedgingPhrases = [
    "it is essential to",
    "it is crucial to",
    "delve into",
    "beacon of",
    "tapestry",
    "testament to",
    "underscores the importance",
    "pivotal role",
    "foster a culture",
    "in today's fast-paced",
    "navigating the complexities",
    "comprehensive approach",
    "vital component",
    "streamline",
  ];

  const matchedHedging = balancedHedgingPhrases.filter((p) =>
    lowerText.includes(p)
  );
  if (matchedHedging.length >= 2) {
    signalPoints += 20;
    characteristics.push({
      id: "synthetic_vocabulary",
      title: "Archetypal LLM Lexical Clustering",
      description: `Contains high-frequency synthetic buzzwords or syntactic tropes commonly found in general-purpose model outputs.`,
      observedEvidence: matchedHedging.join(", "),
    });
  }

  // 5. Lexical Diversity (TTR)
  // LLMs typically balance rich vocabulary with high repetition avoidance,
  // showing TTR around 0.65-0.85 without typos or vernacular slang.
  const hasSlangOrTypos = /[b-df-hj-np-tv-z]{5,}|(ur|u|plz|thx|gonna|wanna|asap)\b/i.test(
    text
  );
  if (
    stats.lexicalDiversityTTR >= 0.68 &&
    stats.lexicalDiversityTTR <= 0.88 &&
    !hasSlangOrTypos &&
    stats.wordCount >= 50
  ) {
    signalPoints += 15;
    characteristics.push({
      id: "pristine_lexicon",
      title: "Pristine Lexical Balance & Zero Vernacular",
      description:
        "Vocabulary exhibits strict grammatical cleanliness with no spelling errors, colloquial shortcuts, or organic idiosyncrasies.",
    });
  }

  // Calculate final signal score capped at 95 (never 100% certainty)
  const signalScore = Math.min(92, Math.max(0, signalPoints));

  let verdict: AIWritingVerdict;
  let verdictLabel: string;
  let signalStrength: SignalStrength;

  if (signalScore >= 60) {
    verdict = "LIKELY_AI";
    verdictLabel = "Likely AI-generated or AI-assisted style";
    signalStrength = "HIGH";
  } else if (signalScore >= 35) {
    verdict = "POSSIBLY_AI";
    verdictLabel = "Possibly AI-assisted";
    signalStrength = "MODERATE";
  } else if (signalScore >= 15) {
    verdict = "NO_STRONG_SIGNALS";
    verdictLabel = "No strong AI-like signals detected";
    signalStrength = "LOW";
  } else {
    verdict = "NO_STRONG_SIGNALS";
    verdictLabel = "No strong AI-like signals detected";
    signalStrength = "VERY_LOW";
  }

  const confidenceNotes =
    signalScore >= 60
      ? "Multiple structural markers (uniform sentence variance, formal connectors, formulaic framing) align with common generative language models."
      : signalScore >= 35
      ? "Some stylistic elements match LLM writing conventions, but could also reflect an articulate human professional following corporate templates."
      : "The text exhibits natural organic variation, colloquial traits, or lacks distinctive synthetic markers.";

  return {
    verdict,
    verdictLabel,
    signalStrength,
    signalScore,
    detectedCharacteristics: characteristics,
    linguisticMetrics: {
      averageSentenceLength: stats.averageSentenceLength,
      sentenceLengthStdDev: stats.sentenceLengthStdDev,
      lexicalDiversityTTR: stats.lexicalDiversityTTR,
      formulaicTransitionCount: stats.transitionPhraseCount,
      uniformityIndex,
    },
    confidenceNotes,
    disclaimer:
      "Experimental heuristic estimate only. This is not validated proof of authorship. AI-generated messages can be entirely benign, and human-written messages can be malicious. Treat this indicator as distinct from cybersecurity risk.",
  };
}
